/**
 * Switch the Prisma datasource from SQLite to PostgreSQL and regenerate the
 * migration history for it.
 *
 * The schema itself is already portable (no native enums, no scalar lists), so
 * only the datasource block changes. The SQLite migrations are archived rather
 * than deleted, in case you want to go back.
 *
 *   node scripts/use-postgres.mjs
 *   npx prisma generate
 *   npx prisma migrate deploy      # uses DIRECT_URL
 *   npm run db:seed
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SCHEMA = "prisma/schema.prisma";
const MIGRATIONS = "prisma/migrations";

const schema = readFileSync(SCHEMA, "utf8");
if (schema.includes('provider = "postgresql"')) {
  console.log("Already on PostgreSQL — nothing to do.");
  process.exit(0);
}
if (!schema.includes('provider = "sqlite"')) {
  console.error("Could not find the sqlite datasource provider in the schema.");
  process.exit(1);
}

// Serverless opens many short-lived connections, so queries go through a
// pooler. Prisma migrations can't run over pgbouncer, so they use directUrl.
const OLD_DATASOURCE = ['  provider = "sqlite"', '  url      = env("DATABASE_URL")'].join("\n");
const NEW_DATASOURCE = [
  '  provider  = "postgresql"',
  '  url       = env("DATABASE_URL")',
  '  directUrl = env("DIRECT_URL")',
].join("\n");

if (!schema.includes(OLD_DATASOURCE)) {
  console.error("The datasource block doesn't look the way this script expects. Edit it by hand.");
  process.exit(1);
}

writeFileSync(SCHEMA, schema.replace(OLD_DATASOURCE, NEW_DATASOURCE));
console.log("✓ datasource → postgresql (with directUrl for migrations)");

// Archive the SQLite migrations; their SQL is not valid Postgres.
if (existsSync(MIGRATIONS)) {
  const archive = `prisma/migrations-sqlite-${Date.now()}`;
  renameSync(MIGRATIONS, archive);
  console.log(`✓ archived SQLite migrations → ${archive}`);
}

// Produce the Postgres DDL without needing a live database.
const sql = execFileSync(
  "npx",
  ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", SCHEMA, "--script"],
  { encoding: "utf8", shell: process.platform === "win32" },
);

const dir = join(MIGRATIONS, "00000000000000_init");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "migration.sql"), sql);
writeFileSync(
  join(MIGRATIONS, "migration_lock.toml"),
  '# Please do not edit this file manually\nprovider = "postgresql"\n',
);
console.log("✓ wrote prisma/migrations/00000000000000_init/migration.sql");
console.log("\nNext: set DATABASE_URL and DIRECT_URL, then `npx prisma migrate deploy && npm run db:seed`.");
